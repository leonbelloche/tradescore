const ROLE = { PG: "guard", SG: "guard", G: "guard", SF: "wing", F: "wing", PF: "big", C: "big" };

// Hollinger Game Score (same formula as in CLAUDE.md).
export function gameScore(s) {
  return s.pts + 0.4 * s.fgm - 0.7 * s.fga - 0.4 * (s.fta - s.ftm) + 0.7 * s.orb + 0.3 * s.drb
    + s.stl + 0.7 * s.ast + 0.7 * s.blk - 0.4 * s.pf - s.tov;
}

function statLine(position, targetGmsc, gp) {
  const base = BASE[ROLE[position]];
  const k = targetGmsc / gameScore(base);
  const line = { gp };
  for (const [key, value] of Object.entries(base)) {
    // Minutes grow slower than production; cap at 38.
    line[key] = key === "min" ? Math.min(38, Math.round(value * Math.sqrt(k) * 10) / 10) : Math.round(value * k * 10) / 10;
  }
  return line;
}

